"""
A tiny internationalisation (i18n) helper for the report and its plots.

The pipeline can produce its report in English (``en``, default) or Polish
(``pl``), selected once per run via ``params.report_language`` and plumbed to
``bin/report.py`` and every plot script exactly like ``params.output_format``.

Design (mirrors bin/decorators.py - an importable module in bin/, already on
the runtime import path, so no data-file staging or Docker rebuild is needed):

* ``CATALOG`` is a plain dict keyed by language then by a stable, dotted,
  surface-first message id (e.g. ``"section.qc.title"``). Rich descriptions keep
  their embedded HTML markup as the catalog value - only the prose is translated.
* ``t(key, lang, **fmt)`` resolves a message id, falling back to English and then
  to the raw key so a missing entry never crashes the report; ``**fmt`` values
  (CpG counts, column names, ...) are substituted with ``str.format``.

The Polish rich-text descriptions below are engineering drafts and should be
reviewed by a methylation-domain Polish speaker (see the multilingual-support
plan, Phase 7 / decision D5). Scientific terms and identifiers (SeSAME, Infinium,
CpG, bisulfite, Kruskal-Wallis, Sentrix_ID, clock names, ...) are kept as-is.
"""

