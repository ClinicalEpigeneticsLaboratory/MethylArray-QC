def t(key: str, lang: str = DEFAULT_LANGUAGE, **fmt) -> str:
    """Translate a message id, with safe fallbacks so the report never crashes.

    Resolution order: requested language -> English -> the raw key. Any
    ``**fmt`` values (e.g. CpG counts, column names) are substituted with
    ``str.format`` only when provided, so plain strings pass through untouched.

    Args:
        key (str): dotted message id, e.g. ``"section.qc.title"``.
        lang (str): target language code (``"en"`` or ``"pl"``); unknown codes
            fall back to English.
        **fmt: values substituted into ``{placeholders}`` in the resolved string.

    Returns:
        str: the localised (and formatted) string.
    """
    s = CATALOG.get(lang, {}).get(key) or CATALOG[DEFAULT_LANGUAGE].get(key) or key
    return s.format(**fmt) if fmt else s


def month_name(month: int, lang: str = DEFAULT_LANGUAGE) -> str:
    """Return the localised month name for a 1-12 month number.

    ``datetime.strftime("%B")`` renders month names in the C locale (always
    English) unless the process locale is changed, and the pl_PL locale is not
    guaranteed to exist in the container. Resolving the name from CATALOG keeps
    the static PDF path localised without a setlocale() call or a new dependency.

    Args:
        month (int): month number, 1 (January) to 12 (December).
        lang (str): target language code; unknown codes fall back to English.

    Returns:
        str: the localised month name.
    """
    return t(f"month.{month:02d}", lang)
